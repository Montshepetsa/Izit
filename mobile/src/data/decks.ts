import type { Prompt } from '../state/gameTypes';

function deck(category: string, family: string[], afterDark: string[]): Prompt[] {
  return [
    ...family.map((answer, i) => ({
      id: `${category.toLowerCase()}-f-${String(i + 1).padStart(2, '0')}`,
      category,
      answer,
      rating: 'family' as const,
    })),
    ...afterDark.map((answer, i) => ({
      id: `${category.toLowerCase()}-a-${String(i + 1).padStart(2, '0')}`,
      category,
      answer,
      rating: 'afterDark' as const,
    })),
  ];
}

